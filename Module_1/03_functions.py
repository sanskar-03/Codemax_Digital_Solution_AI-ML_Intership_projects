
# Defining a basic function with a parameter
def greet_user(name):
    """This function prints a greeting."""
    print(f"Hello there, {name}!")

# Defining a function that returns a value
def calculate_area(length, width):
    """This function calculates and returns the area of a rectangle."""
    area = length * width
    return area

# Calling the functions
greet_user("Sarah")

# Storing the returned value in a variable
rect_area = calculate_area(5, 10)
print(f"The area of the rectangle is: {rect_area}")

