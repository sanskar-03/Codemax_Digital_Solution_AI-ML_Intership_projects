
# For Loops
print("Counting to 5 using a for loop:")
for number in range(1, 6):
    print(number)

# Iterating through a list
colors = ["red", "green", "blue"]
print("\nIterating through a list:")
for color in colors:
    print(f"Color: {color}")

# While Loop
print("\nCountdown using a while loop:")
countdown = 3
while countdown > 0:
    print(countdown)
    countdown -= 1
    
